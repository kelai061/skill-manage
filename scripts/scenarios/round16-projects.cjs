'use strict';
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('original-fs');
module.exports = async ({ app, win, delay }) => {
  const store = require(path.join(app.getAppPath(), 'main/store'));
  const scanner = require(path.join(app.getAppPath(), 'main/scanner'));
  const base = path.join(app.getPath('userData'), 'round16-fixture');
  const project = path.join(base, 'project');
  const empty = path.join(base, 'empty');
  for (const d of [path.join(project, 'v1', 'same'), path.join(project, 'v2', 'same'), empty]) fs.mkdirSync(d, {recursive:true});
  fs.writeFileSync(path.join(project, 'v1', 'same', 'SKILL.md'), '---\nname: same\ndescription: first version\n---\n# first\n');
  fs.writeFileSync(path.join(project, 'v2', 'same', 'SKILL.md'), '---\nname: same\ndescription: second version\n---\n# second\n');
  const p = { id:'round16-product', name:'Fixture', launchPath:base, projects:[{id:'round16-project', name:'Project', path:project}, {id:'round16-empty', name:'Empty', path:empty}] };
  const a = scanner.readSkillMeta(path.join(project, 'v1', 'same'), 'project', p.id, 'round16-project');
  const b = scanner.readSkillMeta(path.join(project, 'v2', 'same'), 'project', p.id, 'round16-project');
  store.get().products.push(p); store.get().skills.push(a,b); store.save();
  const js = code => win.webContents.executeJavaScript(code, true);
  await js(`(async()=>{const {state,refresh}=await import('app://local/js/state.js'); await refresh('data'); state.productId='round16-product'; state.scope='project'; state.projectId=null; window.__goto('skills');})()`);
  await delay(400);
  assert.equal(await js(`document.querySelector('.empty-projects').open`), false);
  assert.equal(await js(`document.querySelectorAll('.empty-projects [data-projcard]').length`), 1);
  await js(`document.querySelector('.empty-projects summary').click()`);
  assert.equal(await js(`document.querySelector('.empty-projects').open`), true);
  await js(`document.querySelector('[data-projcard="round16-project"]').click()`); await delay(400);
  assert.equal(await js(`document.querySelectorAll('.skill-versions').length`), 1);
  assert.equal(await js(`document.querySelector('.skill-versions').open`), false);
  assert.equal(await js(`document.querySelectorAll('.skill-versions [data-id]').length`), 2);
  await js(`document.querySelector('.skill-versions summary').click()`);
  assert.equal(await js(`document.querySelector('.skill-versions').open`), true);
  assert.equal(await js(`new Set([...document.querySelectorAll('.skill-versions [data-id]')].map(x=>x.dataset.id)).size`), 2);
  const id = a.id;
  await js(`window.atelier.call('config:patch', {customDescriptions:{[${JSON.stringify(id)}]:'自定义说明 fixture'}})`);
  await js(`(async()=>{const {refresh}=await import('app://local/js/state.js'); await refresh('data');})()`); await delay(400);
  assert.equal(await js(`document.querySelector('[data-id=${JSON.stringify(id)}] .description-flip__back').textContent.includes('自定义说明 fixture')`), true);
  assert.equal(fs.readFileSync(a.path, 'utf8').includes('自定义说明 fixture'), false);
  await js(`window.__goto('products')`); await delay(400);
  assert.equal(await js(`document.querySelector('[data-pid="round16-product"] .empty-projects').open`), false);
  assert.equal(await js(`document.querySelector('[data-pid="round16-product"] .empty-projects [data-prid="round16-empty"]') !== null`), true);
  console.log('[PASS] Same-name versions preserve distinct entries, empty projects fold in both views, personal description persists without modifying skill');
  return {ok:true};
};
