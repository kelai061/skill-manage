'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const Module = require('node:module');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'atelier-agent-'));
const handlers = new Map();
let copied = '';
process.argv.push('--profile=' + root);
const load = Module._load;
Module._load = function(name, parent, main) {
  if (name === 'electron') return { app: { getPath: () => root, getVersion: () => 'test' }, clipboard: { writeText: text => { copied = text; } }, ipcMain: { handle: (name, fn) => handlers.set(name, fn) } };
  return load.call(this, name, parent, main);
};
const store = require('../main/store');
const skills = require('../main/skillService');
const agent = require('../main/agentTranslation');
const ai = require('../main/aiService');
const ipc = require('../main/ipc');

async function main() {
  const disk = require('../main/translationStorage');
  const helper = require('../main/translationTasks');
  const file = path.join(root, 'SKILL.md');
  const content = '# English heading\n\nAlready translated prose.\n\n这是中文 API 文档。\n\nTranslate this new paragraph.\n\n```js\nconst secret = 1;\n```';
  fs.writeFileSync(file, content);
  const old = path.join(root, 'translations'); fs.mkdirSync(old);
  const legacyName = `seg-zh-CN-${skills.sha1('__agent__').slice(0, 8)}.json`;
  const legacyKey = skills.sha1('Legacy saved paragraph.');
  fs.writeFileSync(path.join(old, legacyName), JSON.stringify({ [legacyKey]: '旧译文' }));
  fs.writeFileSync(path.join(old, legacyName + '.bak-user'), 'original-backup');
  store.patch({ skills: [{ id: 'test', path: file, dir: root }] });
  assert.equal(store.paths.translations, path.join(root, 'app-root', 'translations'));
  assert(!fs.existsSync(old), 'legacy active data moved out of user-data translations');
  assert.equal(fs.readFileSync(path.join(store.paths.translations, 'migration-backups', legacyName + '.bak-user'), 'utf8'), 'original-backup');
  assert.equal(disk.readMap(disk.agentFile(store.paths.translations, 'zh-CN', legacyKey))[legacyKey], '旧译文');
  const lock = path.join(store.paths.translations, '.agent-write.lock');
  fs.mkdirSync(lock); disk.writeJson(path.join(lock, 'owner.json'), { pid: process.pid, token: 'active-test' });
  assert.throws(() => disk.withLock(store.paths.translations, () => {}), /另一个任务/);
  fs.unlinkSync(path.join(lock, 'owner.json')); fs.rmdirSync(lock);
  fs.mkdirSync(lock); disk.writeJson(path.join(lock, 'owner.json'), { pid: 2147483647, token: 'interrupted-test' });
  assert.equal(disk.withLock(store.paths.translations, () => 'recovered'), 'recovered');
  assert(!fs.existsSync(lock), 'interrupted writer lock can be recovered without losing data');
  skills.commitSegCache({}, 'zh-CN', ai.cfg().model, ['Already translated prose.'], ['已翻译内容。']);
  ipc.register();
  const call = (name, payload) => handlers.get(name)(null, payload);
  let requests = 0;
  ai.translateSegments = async texts => { requests++; await new Promise(r => setTimeout(r, 15)); return texts.map(t => '译文 ' + t); };
  const task = (await call('translation:agent', { id: 'test' })).data;
  assert.equal(task.count, 2);
  assert(task.taskFile.startsWith(path.join(root, 'app-root', 'translation-tasks')));
  assert(copied.includes('complete=true') && copied.includes('每次只读取一批'));
  const manifest = JSON.parse(fs.readFileSync(task.taskFile, 'utf8'));
  assert.equal(manifest.total, 2);
  const batch = helper.next(task.taskFile);
  assert.deepEqual(batch.items.map(item => item.text), ['English heading', 'Translate this new paragraph.']);
  const resultFile = path.join(path.dirname(task.taskFile), 'result.json');
  const result = { translations: batch.items.map(item => ({ key: item.key, text: '智能体持久译文 ' + item.key.slice(0, 4) })) };
  fs.writeFileSync(resultFile, JSON.stringify({ translations: result.translations.slice(0, 1) }));
  assert.throws(() => helper.commit(task.taskFile, batch.file, resultFile), /缺少/);
  assert.equal(helper.status(task.taskFile).saved, 0, 'partial batch is not marked saved');
  fs.writeFileSync(file, content + '\nChanged source.');
  fs.writeFileSync(resultFile, JSON.stringify(result));
  assert.throws(() => helper.commit(task.taskFile, batch.file, resultFile), /原文已变化/);
  assert.equal(helper.status(task.taskFile).changed, 2);
  fs.writeFileSync(file, content);
  helper.commit(task.taskFile, batch.file, resultFile);
  assert.equal(helper.status(task.taskFile).complete, true);
  const fresh = require('node:child_process').spawnSync(process.execPath, [path.resolve('main/translationTasks.js'), 'status', task.taskFile], { encoding: 'utf8' });
  assert.equal(fresh.status, 0, fresh.stderr);
  assert.equal(JSON.parse(fresh.stdout).saved, 2, 'fresh process verifies persistent disk contents');
  const translated = await call('ai:translate', { id: 'test' });
  assert.equal(translated.data.offline, true);
  assert.equal(requests, 0);
  assert.equal(fs.readFileSync(file, 'utf8'), content);
  assert.equal((await call('translation:agent', { id: 'test' })).data.count, 0);
  // Fake progress must never hide deleted or missing stored translations.
  const first = batch.items[0], shard = disk.agentFile(store.paths.translations, 'zh-CN', first.key);
  const map = disk.readMap(shard); delete map[first.key]; disk.writeJson(shard, map);
  disk.writeJson(path.join(path.dirname(task.taskFile), 'progress.json'), { complete: true });
  assert.equal(helper.status(task.taskFile).complete, false);
  assert.equal(helper.next(task.taskFile).items.length, 1);
  helper.commit(task.taskFile, batch.file, resultFile);
  assert.equal(helper.status(task.taskFile).complete, true);
  skills.clearCache();
  assert.equal(disk.readMap(shard)[first.key], result.translations[0].text, 'saved agent translations survive temporary-cache cleanup');
  assert.equal((await call('translation:word', { text: 'word' })).ok, false);
  store.patch({ settings: { translate: { selectionLive: true } } });
  const words = await Promise.all([call('translation:word', { text: 'word' }), call('translation:word', { text: 'word' })]);
  assert(words.every(r => r.ok)); assert.equal(requests, 1);
  store.patch({ settings: { translate: { selectionLive: false } } });
  const brief = await call('app:copyBrief');
  assert(brief.data.text.includes('按当前任务挑出相关的 skill') && !copied.includes('任务索引'));
  fs.writeFileSync(file, Array.from({length:80}, (_, i) => `Pending paragraph number ${i}.`).join('\n\n'));
  const complete = (await call('translation:batch')).data;
  assert.equal(complete.count, 80);
  const all = JSON.parse(fs.readFileSync(complete.taskFile, 'utf8'));
  assert.equal(all.batches.length, 4);
  assert(all.batches.every(info => info.count <= 20));
  const firstBatch = helper.next(complete.taskFile);
  disk.writeJson(resultFile, { translations: firstBatch.items.map(item => ({ key: item.key, text: '已保存的批次译文' })) });
  helper.commit(complete.taskFile, firstBatch.file, resultFile);
  assert.equal(helper.status(complete.taskFile).pending, 60);
  assert.equal(helper.next(complete.taskFile).file, all.batches[1].file, 'resume goes to first unsaved batch');
  assert.equal((await call('translation:batch')).data.count, 60, 'new instruction excludes every saved segment');
  assert(!handlers.has('translation:import') && !handlers.has('translation:batchImport'));
  console.log('PASS durable root storage: migration, disk verification in fresh process, bounded batches, missing/changed rejection, resumability, fake-progress detection, no API calls');
}
main().catch(e => { console.error(e); process.exitCode = 1; }).finally(() => {
  Module._load = load;
  const resolved = path.resolve(root);
  if (!resolved.startsWith(path.resolve(os.tmpdir()) + path.sep) || !path.basename(resolved).startsWith('atelier-agent-')) throw new Error('Unsafe cleanup');
  fs.rmSync(resolved, { recursive: true, force: true });
});
